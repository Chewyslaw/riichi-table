// Builds public/emoji-data.js: every emoji, grouped as in the Unicode chart, with search words.
// Dev-only; the app has no runtime dependency on these packages. To refresh after a new Unicode release:
//   npm install --no-save unicode-emoji-json emojilib emojibase-data && node scripts/build-emoji.mjs
// (or pass the folder that holds node_modules:  node scripts/build-emoji.mjs /path/to/dir)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const base = path.resolve(process.argv[2] || path.join(here, '..'));
const require = createRequire(path.join(base, 'package.json'));
const groups = require('unicode-emoji-json/data-by-group.json');
const words = require('emojilib');
const version = require('unicode-emoji-json/package.json').version;
// :shortcodes: as people know them from GitHub, Slack and Discord (":joy:", ":+1:", ":thumbsup:")
const shortSets = ['github', 'iamcal', 'emojibase'].map((n) => require(`emojibase-data/en/shortcodes/${n}.json`));
const hexOf = (emoji) => Array.from(emoji).map((c) => c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')).filter((h) => h !== 'FE0F').join('-');
const shortIndex = shortSets.map((set) => new Map(Object.entries(set).map(([hex, v]) => [hex.split('-').filter((h) => h !== 'FE0F').join('-'), [].concat(v)])));
function shortcodes(e) {
  const hex = hexOf(e.emoji);
  const out = [];
  for (const idx of shortIndex) for (const c of idx.get(hex) || []) { const k = c.toLowerCase().replace(/-/g, '_'); if (/^[a-z0-9_+]+$/.test(k) && !out.includes(k)) out.push(k); }
  if (!out.length) out.push(e.slug.toLowerCase().replace(/[^a-z0-9_+]+/g, '_').replace(/^_+|_+$/g, '')); // always at least one: the official name
  return out.slice(0, 5);
}

const STOP = new Set(['a', 'an', 'the', 'of', 'with', 'and', 'in', 'on', 'for', 'to', 'face', 'symbol', 'sign', 'button']);
let count = 0;
const out = groups.map((g) => {
  const rows = g.emojis.map((e) => {
    // search words: the official name first, then common keywords (each word once, lower case, no punctuation)
    const seen = new Set();
    const add = (s) => String(s).toLowerCase().replace(/[_\-:,.()“”"'’!&]+/g, ' ').split(/\s+/).filter(Boolean).forEach((w) => { if (!seen.has(w)) seen.add(w); });
    add(e.name);
    const nameWords = seen.size;
    for (const k of words[e.emoji] || []) add(k);
    const all = [...seen];
    const extra = all.slice(nameWords).filter((w) => !STOP.has(w) && w.length > 1).slice(0, 10);
    count++;
    // emoji ␟ name ␟ extra search words ␟ flags (t = takes a skin tone) ␟ emoji version when recent (older ones are everywhere) ␟ shortcodes
    const v = parseFloat(e.emoji_version) >= 13 ? e.emoji_version : '';
    return [e.emoji, e.name, extra.join(' '), e.skin_tone_support ? 't' : '', v, shortcodes(e).join(' ')].join('\t');
  });
  return [g.name, rows.join('\n')];
});
const body = `// Generated by scripts/build-emoji.mjs from unicode-emoji-json ${version} (names, groups), emojilib (search words) and emojibase-data (shortcodes). Do not edit.
// ${count} emoji. Each line: emoji, name, extra search words, "t" if it takes a skin tone, emoji version if 13 or newer, :shortcodes: (tab-separated).
export const EMOJI_GROUPS = ${JSON.stringify(out)};
`;
const file = path.join(here, '..', 'public', 'emoji-data.js');
fs.writeFileSync(file, body);
console.log(`${count} emoji in ${out.length} groups → ${file} (${(body.length / 1024).toFixed(0)} KB)`);
